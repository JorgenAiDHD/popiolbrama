import { chromium } from 'playwright';
import { createServer } from 'vite';
const server = await createServer({ server: { port: 5194, host: '127.0.0.1' }, logLevel: 'error' });
await server.listen();
const browser = await chromium.launch({ args: ['--use-gl=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const ctx = await browser.newContext({ viewport: { width: 1280, height: 720 } });
await ctx.addInitScript(() => localStorage.setItem('popiolbrama.meta2', JSON.stringify({ classes: ['wojownik', 'mag', 'lowca', 'czarnoksieznik'], mute: true, hq: true })));
const page = await ctx.newPage();
page.on('pageerror', e => console.log('pageerror', e.message));
await page.goto('http://127.0.0.1:5194/?debug');
await page.waitForSelector('#go');
await page.click('#cl .cls:nth-child(2)');
await page.waitForTimeout(1500);
await page.screenshot({ path: 'shot-menu.png' });
await page.click('#go');
await page.waitForTimeout(12000);
await page.evaluate(() => window.__g.god(true));
await page.screenshot({ path: 'shot-play1.png' });
await page.evaluate(() => { window.__g.warp(130); window.__g.xp(150); });
const pick = async () => { for (let i = 0; i < 20; i++) { if (!(await page.isVisible('#lvl'))) return; await page.waitForTimeout(450); if (i === 1) await page.screenshot({ path: 'shot-cards.png' }); await page.click('#lvl .card'); await page.waitForTimeout(120); } };
await page.waitForTimeout(600); await pick();
await page.waitForTimeout(5000);
await page.screenshot({ path: 'shot-boss.png' });
await page.evaluate(() => { window.__g.warp(190); window.__g.maxall(); });
await page.waitForTimeout(7000); await pick();
await page.screenshot({ path: 'shot-las.png' });
await page.keyboard.press('KeyC');
await page.waitForTimeout(400);
await page.screenshot({ path: 'shot-sheet.png' });
await browser.close(); await server.close();

