import { chromium, devices } from 'playwright';
import { createServer } from 'vite';
const server = await createServer({ server: { port: 5187, host: '127.0.0.1' }, logLevel: 'error' });
await server.listen();
const browser = await chromium.launch({ args: ['--use-gl=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const ctx = await browser.newContext({ ...devices['Pixel 7'], viewport: { width: 360, height: 640 } });
await ctx.addInitScript(() => localStorage.setItem('popiolbrama.meta2', JSON.stringify({ ash: 300, classes: ['wojownik', 'mag', 'lowca', 'czarnoksieznik', 'paladyn', 'lotr', 'druid', 'szaman'], mute: true, hq: false })));
const page = await ctx.newPage();
const errs = [];
page.on('pageerror', e => errs.push(e.message));
await page.goto('http://127.0.0.1:5187/?debug');
await page.waitForSelector('#go');
await page.waitForTimeout(600);
await page.evaluate(() => document.getElementById('rd').scrollIntoView());
await page.screenshot({ path: 'shots/tel-menu.png' });
await page.tap('#go');
await page.evaluate(() => { const g = window.__g; g.god(true); g.noSpawn(); g.gold(300); });
await page.waitForTimeout(800);
console.log('przyciski dotykowe po starcie (bez dotykania):', 'unik', await page.locator('#dodge').isVisible(), 'fiolka', await page.locator('#potion').isVisible());
await page.screenshot({ path: 'shots/tel-walka.png' });
await page.tap('#invbtn');
await page.waitForSelector('#inv:not(.hide)');
await page.waitForTimeout(300);
await page.screenshot({ path: 'shots/tel-ekwipunek.png' });
await page.tap('#invx');
await page.evaluate(() => window.__g.openTown());
await page.waitForSelector('#town:not(.hide) .tcard');
await page.waitForTimeout(400);
await page.screenshot({ path: 'shots/tel-przystan.png', fullPage: false });
const over = await page.evaluate(() => { const t = document.getElementById('town'); return { sw: t.scrollWidth, cw: t.clientWidth, sh: t.scrollHeight, ch: t.clientHeight }; });
console.log('przystan overflow poziomy:', over.sw > over.cw, JSON.stringify(over));
await page.tap('#townx');
